"""Fault experiments generated from the SLOs an application declares (P6): declaring an SLO is enough to have it
tested daily by the regression. Generation happens when you author, never when the regression runs: the predictions
are in a file you read and commit before the first run, and a wrong one is a finding (docs/experiments.md).

  python3 scripts/generate-experiments.py [--apps DIR] [--env dev,staging] [--missing] [--force] [--dry-run]
  python3 scripts/generate-experiments.py --check [--apps DIR]

For every SLO of every <DIR>/<app>/app.yaml (default DIR: apps) and environment (default: the first environment
that is not named prod / production and has the SLO), from experiments/templates/<SLI type>.yaml:

  <DIR>/<app>/experiments/generated/<app>-<slo>-<env>.yaml

(the file name is the experiment's name: unique across applications, as the results and metrics need). What each
type predicts and why: experiments/templates/README.md. A file is written only when everything it needs can be derived
from the application's own files — the pods to fail (the SLO's matchers against the pod labels of its manifests, or
the probed Service's selector) — otherwise the SLO is listed as skipped, with the reason. Nothing is ever guessed.

  --env A,B    these environments instead of the default (an SLO not rendered in one is skipped there)
  --missing    only SLOs that no experiment covers yet (see --check)
  --force      rewrite generated files that exist (only files with a `generated:` field; never hand-written ones)
  --dry-run    say what would be written, write nothing
  --check      the coverage gate: exit 1 when a declared SLO is named by no non-skipped experiment's expect.fire
               (hand-written or generated), or a generated file names an SLO that is no longer declared

Exit 0 / 1 (--check: uncovered or orphaned; otherwise: a file failed its own validation, which is a bug here).
"""
import argparse
import glob
import math
import os
import re
import string
import sys
import textwrap

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
try:
    import yaml
except ImportError:  # pragma: no cover
    sys.exit("PyYAML is required (apt install python3-yaml, or pip install pyyaml)")
import experiment  # noqa: E402  (format and deadline checks: a generated file must pass what the runner checks)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TEMPLATES = os.path.join(ROOT, "experiments", "templates")
VERSION = 1                       # of the templates: bump when a template's predictions change
TYPES = ("availability", "latency", "probe", "age", "ratio", "bool")
PROD = re.compile(r"(prod|production)")
POD_KINDS = {"Deployment", "StatefulSet", "DaemonSet", "ReplicaSet", "Rollout", "Job"}
MATCHER = re.compile(r'\s*([A-Za-z_][A-Za-z0-9_]*)\s*(=~|!~|!=|=)\s*"((?:[^"\\]|\\.)*)"\s*(?:,|$)')
PLAIN = re.compile(r"[A-Za-z][A-Za-z0-9._/-]*")
YAML_WORDS = {"true", "false", "yes", "no", "on", "off", "null", "y", "n", "~"}
# Pyrra's fast burn: 14 × the budget rate over 1h (and 5m), `for: 2m` (docs/experiments.md)
FAST_FACTOR, FAST_FOR_MIN, MARGIN_MIN, MIN_WITHIN, MAX_WITHIN = 14, 2, 4, 8, 30
# SLOMetricAbsent: Pyrra's rule waits `for` 6m (10m for a latency SLI) in a group evaluated every 150s; the runner
# sees such alerts up to ~2.3 min late (storefront-db-unreachable-v2: fired 8.7 min, seen 10.9). Bound: for + 8 min.
ABSENT_FOR = {"latency": 10}
ABSENT_FOR_DEFAULT, ABSENT_MARGIN = 6, 8
HEADER = ("# generated by scripts/generate-experiments.py from {app}/app.yaml — edit freely; regenerate with --force\n"
          "# (template experiments/templates/{type}.yaml, version {version}; what it predicts and why: its comments)\n")


def say(msg):
    print(msg, flush=True)


# ---------------------------------------------------------------- reading the application (pure)

def parse_matchers(s):
    """'app="web", route=~"GET .*"' → [(label, op, value)]; ValueError on anything else."""
    out, pos, s = [], 0, (s or "").strip()
    while pos < len(s):
        m = MATCHER.match(s, pos)
        if not m:
            raise ValueError(f"cannot read matchers {s!r}")
        out.append((m.group(1), m.group(2), m.group(3)))
        pos = m.end()
    return out


def manifests(app_dir):
    """Every parsable Kubernetes object in the application's files (not app.yaml, not experiments/). Helm templates
    that are not YAML are skipped: what they hold cannot be derived without rendering."""
    out = []
    for f in sorted(glob.glob(os.path.join(app_dir, "**", "*.y*ml"), recursive=True)):
        rel = os.path.relpath(f, app_dir)
        if rel == "app.yaml" or rel.split(os.sep)[0] == "experiments":
            continue
        try:
            with open(f, encoding="utf-8") as fh:
                docs = list(yaml.safe_load_all(fh))
        except (yaml.YAMLError, UnicodeDecodeError):
            continue
        out += [d for d in docs if isinstance(d, dict) and d.get("kind")]
    return out


def pod_labels(objs):
    """The literal label sets of the pods the manifests create."""
    out = []
    for o in objs:
        spec = o.get("spec") or {}
        if o["kind"] in POD_KINDS:
            labels = ((spec.get("template") or {}).get("metadata") or {}).get("labels")
        elif o["kind"] == "CronJob":
            labels = ((((spec.get("jobTemplate") or {}).get("spec") or {}).get("template") or {}).get("metadata") or {}).get("labels")
        elif o["kind"] == "Pod":
            labels = (o.get("metadata") or {}).get("labels")
        else:
            continue
        if isinstance(labels, dict) and all(isinstance(v, str) for v in labels.values()):
            out.append(labels)
    return out


def service_selector(objs, name):
    """The literal selector of Service <name>, or None."""
    for o in objs:
        if o["kind"] == "Service" and (o.get("metadata") or {}).get("name") == name:
            sel = (o.get("spec") or {}).get("selector")
            if isinstance(sel, dict) and sel and all(isinstance(v, str) for v in sel.values()):
                return sel
    return None


def selector_from_matchers(matchers, pods):
    """The pod selector an SLI's matchers name: its equality matchers whose label and value some pod of the manifests
    carries (PodMonitor podTargetLabels copy pod labels onto the series, e.g. app). (selector, None) or (None, why)."""
    try:
        eq = [(k, v) for k, op, v in parse_matchers(matchers) if op == "="]
    except ValueError as e:
        return None, str(e)
    sel = {k: v for k, v in eq if any(p.get(k) == v for p in pods)}
    if not sel:
        return None, (f"no equality matcher of {matchers!r} is a pod label in the manifests"
                      if matchers else "no matchers: which pods export the metric cannot be derived")
    if not any(all(p.get(k) == v for k, v in sel.items()) for p in pods):
        return None, f"no pod in the manifests carries all of {sel}"
    return sel, None


def slo_kind(slo):
    kinds = [t for t in TYPES if t in slo]
    return kinds[0] if len(kinds) == 1 else None


def environments(app, slo, wanted=None):
    """The environments to generate for: `wanted` (those the SLO is rendered in), else the first non-prod one."""
    envs = [e["name"] for e in app.get("environments", []) if not slo.get("environments") or e["name"] in slo["environments"]]
    if wanted:
        return [e for e in wanted if e in envs]
    return [e for e in envs if not PROD.fullmatch(e)][:1]


# ---------------------------------------------------------------- what one SLO becomes (pure)

def fmt_min(m):
    return f"{int(m)}m"


def flow(d):
    """A flat dict as a YAML flow mapping, quoting only what needs it."""
    def q(s):
        s = str(s)
        return s if PLAIN.fullmatch(s) and s.lower() not in YAML_WORDS else "'" + s.replace("'", "''") + "'"
    return "{ " + ", ".join(f"{q(k)}: {q(v)}" for k, v in d.items()) + " }"


def squote(s):
    return "'" + s.replace("'", "''") + "'"


def probe_bound(objective):
    """(minutes of total outage to reach fast burn, `within` in minutes) or (None, why)."""
    budget = 100 - float(objective)
    if budget <= 0:
        return None, f"objective {objective}%: no error budget, nothing can burn"
    fraction = FAST_FACTOR * budget / 100      # the share of the hour that must fail
    if fraction >= 1:
        return None, (f"objective {objective}%: fast burn needs {FAST_FACTOR} × {budget:g}% > 100% of the hour to "
                      "fail — it cannot fire (medium burn, 6h, is too long for a daily experiment)")
    burn = fraction * 60
    within = max(MIN_WITHIN, math.ceil(burn + FAST_FOR_MIN + MARGIN_MIN))
    if within > MAX_WITHIN:
        return None, (f"objective {objective}%: fast burn needs {burn:.0f} min of total outage (+ for 2m): over the "
                      f"{MAX_WITHIN} min a generated experiment may hold a fault; write it by hand if you mean it")
    return (round(burn, 1), within), None


def plan_slo(app, slo, env, objs):
    """(fields for the template, None) or (None, why it is skipped)."""
    kind = slo_kind(slo)
    if not kind:
        return None, "not exactly one SLI type"
    sli, name, ns = slo[kind], f"{app['name']}-{slo['name']}", f"{app['name']}-{env}"
    pods = pod_labels(objs)
    f = {"app": app["name"], "env": env, "namespace": ns, "slo": slo["name"], "slo_id": name, "kind": kind,
         "objective": slo.get("objective")}
    if kind == "probe":
        if sli.get("url") or not sli.get("service"):
            return None, "probes a url, not a Service of the application: which pods to fail cannot be derived"
        sel = service_selector(objs, sli["service"])
        if not sel:
            return None, f"Service {sli['service']} with a literal selector not found in the manifests"
        bound, why = probe_bound(slo.get("objective", 0))
        if not bound:
            return None, why
        burn, within = bound
        f.update(service=sli["service"], target=f"{sli.get('path', '/')}",
                 budget=f"{100 - float(slo['objective']):g}", burn_minutes=f"{burn:g}", margin=str(MARGIN_MIN),
                 effect_query=squote(f'max(probe_success{{namespace="{ns}", slo_probe="{name}"}}) == 0'),
                 within_m=within)
    else:
        if kind == "ratio":
            e, t = sli.get("errors") or {}, sli.get("total") or {}
            sel, why = selector_from_matchers(e.get("matchers"), pods)
            sel_t, why_t = selector_from_matchers(t.get("matchers"), pods)
            if not sel or not sel_t:
                return None, why or why_t
            if sel != sel_t:
                return None, f"errors and total come from different pods ({sel} / {sel_t}): no single generic fault"
            metric, matchers = t["metric"], t.get("matchers")
            sli_text = f"{e['metric']} among {t['metric']}{{{t.get('matchers')}}}"
        else:
            sel, why = selector_from_matchers(sli.get("matchers"), pods)
            if not sel:
                return None, why
            metric = sli["metric"] + ("_count" if kind == "latency" else "")
            matchers = sli.get("matchers")
            sli_text = f"{metric}{{{matchers}}}"
        q = ", ".join(x for x in (f'namespace="{ns}"', matchers) if x)
        absent_for = ABSENT_FOR.get(kind, ABSENT_FOR_DEFAULT)
        f.update(sli=sli_text, effect_query=squote(f"absent({metric}{{{q}}})"), absent_for=f"{absent_for}m",
                 within_m=absent_for + ABSENT_MARGIN)
    f["selector"] = flow(sel)
    f["selector_dict"] = sel
    f["selector_text"] = ", ".join(f"{k}={v}" for k, v in sel.items())
    f["fault_name"] = (re.sub(r"[^a-z0-9-]", "-", name.lower())[:52].strip("-") + "-generated")
    f["within"] = fmt_min(f["within_m"])
    f["timeout"] = fmt_min(f["within_m"] + 2)
    f["duration"] = fmt_min(f["within_m"] + 2 + 15)     # ≥ the experiment's time: ends by itself if the runner dies
    return f, None


def may_fire(app, slo, env):
    """The application's other SLOs in that namespace: an outage burns several (any window, any severity)."""
    ns = f"{app['name']}-{env}"
    others = [s for s in app.get("slos", []) if s["name"] != slo["name"]
              and (not s.get("environments") or env in s["environments"])]
    if not others:
        return "[]"
    return "".join(f"\n    - {{ alert: ErrorBudgetBurn, labels: {{ namespace: {ns}, slo: {app['name']}-{s['name']} }} }}"
                   for s in others)


def read_template(kind, templates=TEMPLATES):
    with open(os.path.join(templates, f"{kind}.yaml"), encoding="utf-8") as fh:
        text = fh.read()
    head, sep, body = text.partition("\n---\n")
    if not sep:
        raise ValueError(f"{kind}.yaml: no '---' line between the template's notes and the experiment")
    return body


def rewrap(text, width=118):
    """Re-wrap the folded hypothesis after substitution (yamllint: lines ≤ 160)."""
    lines, out, i = text.split("\n"), [], 0
    while i < len(lines):
        out.append(lines[i])
        if lines[i].endswith(": >-"):
            block = []
            i += 1
            while i < len(lines) and lines[i].startswith("  "):
                block.append(lines[i].strip())
                i += 1
            out += textwrap.wrap(" ".join(block), width, initial_indent="  ", subsequent_indent="  ",
                                 break_on_hyphens=False, break_long_words=False)
            continue
        i += 1
    return "\n".join(l.rstrip() for l in out)


def render(app, slo, f, templates=TEMPLATES):
    """The experiment file's text."""
    body = string.Template(read_template(f["kind"], templates)).substitute(
        {**{k: str(v) for k, v in f.items()}, "may_fire": may_fire(app, slo, f["env"])})
    return (HEADER.format(app=app["dir"], type=f["kind"], version=VERSION) + rewrap(body).rstrip("\n") + "\n"
            + f"generated: {{ from: {slo['name']}, template: {f['kind']}, version: {VERSION} }}\n")


def validate(text, f):
    """What experiment.py checks before a run, plus what the generator meant: [problems]."""
    try:
        x = yaml.safe_load(text)
    except yaml.YAMLError as e:
        return [f"not YAML: {e}"]
    out = experiment.check_format(x) + experiment.check_deadlines(x)
    if x.get("namespace") != f["namespace"]:
        out.append(f"namespace {x.get('namespace')} != {f['namespace']}")
    if x["fault"][0]["spec"]["selector"]["labelSelectors"] != f["selector_dict"]:
        out.append(f"selector {x['fault'][0]['spec']['selector']} != {f['selector_dict']}")
    if [w["labels"]["slo"] for w in x["expect"]["fire"]] != [f["slo_id"]]:
        out.append("expect.fire does not name the SLO")
    if len(max(text.split("\n"), key=len)) > 160:
        out.append("a line longer than 160 characters (yamllint)")
    return out


# ---------------------------------------------------------------- the instance

def load_apps(apps_dir):
    out = []
    for f in sorted(glob.glob(os.path.join(apps_dir, "*", "app.yaml"))):
        with open(f, encoding="utf-8") as fh:
            d = yaml.safe_load(fh) or {}
        d["dir"] = os.path.join(os.path.basename(os.path.abspath(apps_dir)), os.path.basename(os.path.dirname(f)))
        d["path"] = os.path.dirname(f)
        out.append(d)
    return out


def experiment_files(apps_dir):
    """{name: path} of every experiment, hand-written and generated."""
    out = {}
    for d in glob.glob(os.path.join(apps_dir, "*", "experiments")):
        for f in experiment.experiment_paths(d):
            out[os.path.splitext(os.path.basename(f))[0]] = f
    return out


def coverage(apps, files):
    """({slo id: [experiment names]} for every declared SLO, [problems of generated files])."""
    declared = {f"{a['name']}-{s['name']}": [] for a in apps for s in a.get("slos", [])}
    owner = {os.path.abspath(a["path"]): a["name"] for a in apps}
    problems = []
    for name, path in sorted(files.items()):
        x = experiment.load_yaml(path) or {}
        g = x.get("generated")
        if isinstance(g, dict):   # <app dir>/experiments/generated/<name>.yaml
            app = owner.get(os.path.abspath(os.path.join(os.path.dirname(path), "..", "..")), "?")
            if f"{app}-{g.get('from')}" not in declared:
                problems.append(f"{os.path.relpath(path)}: generated from SLO {g.get('from')!r}, which {app} no longer "
                                "declares (delete the file)")
        if x.get("skip"):
            continue
        for w in (x.get("expect") or {}).get("fire") or []:
            slo = (w.get("labels") or {}).get("slo")
            if slo in declared and name not in declared[slo]:
                declared[slo].append(name)
    return declared, problems


def check(apps_dir):
    apps = load_apps(apps_dir)
    cov, problems = coverage(apps, experiment_files(apps_dir))
    for slo, names in sorted(cov.items()):
        say(f"{'✓' if names else '✗'} {slo}: {', '.join(names) if names else 'no experiment names it in expect.fire'}")
    for p in problems:
        say(f"✗ {p}")
    missing = [s for s, n in cov.items() if not n]
    if missing or problems:
        say(f"{len(missing)} of {len(cov)} SLO(s) not covered, {len(problems)} orphaned file(s): "
            "scripts/generate-experiments.py [--missing] writes the generic ones")
        return 1
    say(f"every SLO ({len(cov)}) is named by an experiment")
    return 0


def generate(apps_dir, envs=None, missing=False, force=False, dry_run=False, templates=TEMPLATES):
    """Write the files; returns (written, kept, skipped, failed) as lists of strings."""
    apps = load_apps(apps_dir)
    files = experiment_files(apps_dir)
    cov, _ = coverage(apps, files) if missing else ({}, [])
    written, kept, skipped, failed = [], [], [], []
    for app in apps:
        objs = manifests(app["path"])
        for slo in app.get("slos", []):
            sid = f"{app['name']}-{slo['name']}"
            if missing and cov.get(sid):
                kept.append(f"{sid}: covered by {', '.join(cov[sid])}")
                continue
            es = environments(app, slo, envs)
            if not es:
                skipped.append(f"{sid}: no environment to test it in"
                               + (f" among {', '.join(envs)}" if envs else " (only prod; name one with --env)"))
                continue
            for env in es:
                f, why = plan_slo(app, slo, env, objs)
                if not f:
                    skipped.append(f"{sid} ({slo_kind(slo) or '?'}): {why}")
                    continue
                name = f"{sid}-{env}"
                out = os.path.join(app["path"], "experiments", "generated", f"{name}.yaml")
                other = files.get(name)
                if other and os.path.abspath(other) != os.path.abspath(out):
                    skipped.append(f"{sid}: an experiment named {name} exists already ({os.path.relpath(other)})")
                    continue
                if os.path.exists(out):
                    if not isinstance((experiment.load_yaml(out) or {}).get("generated"), dict):
                        skipped.append(f"{sid}: {os.path.relpath(out)} has no `generated:` field: hand-written, kept")
                        continue
                    if not force:
                        kept.append(f"{os.path.relpath(out)} exists (regenerate with --force)")
                        continue
                text = render(app, slo, f, templates)
                problems = validate(text, f)
                if problems:
                    failed.append(f"{os.path.relpath(out)}: " + "; ".join(problems))
                    continue
                if not dry_run:
                    os.makedirs(os.path.dirname(out), exist_ok=True)
                    with open(out, "w", encoding="utf-8") as fh:
                        fh.write(text)
                written.append(f"{os.path.relpath(out)} ({f['kind']}: {f['fault_name']}, within {f['within']})")
    return written, kept, skipped, failed


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--apps", default="apps", help="the applications' directory (default: %(default)s)")
    p.add_argument("--env", help="environments, comma-separated (default: the first non-prod one of each SLO)")
    p.add_argument("--missing", action="store_true", help="only SLOs no experiment covers yet")
    p.add_argument("--force", action="store_true", help="rewrite existing generated files")
    p.add_argument("--dry-run", action="store_true")
    p.add_argument("--check", action="store_true", help="the coverage gate (writes nothing)")
    a = p.parse_args(argv)
    if not glob.glob(os.path.join(a.apps, "*", "app.yaml")):
        say(f"no {a.apps}/*/app.yaml")
        return 1
    if a.check:
        return check(a.apps)
    envs = [e.strip() for e in a.env.split(",") if e.strip()] if a.env else None
    written, kept, skipped, failed = generate(a.apps, envs, a.missing, a.force, a.dry_run)
    for w in written:
        say(f"{'would write' if a.dry_run else 'wrote'} {w}")
    for k in kept:
        say(f"= {k}")
    for s in skipped:
        say(f"- skipped {s}")
    for x in failed:
        say(f"✗ {x}")
    say(f"{len(written)} written, {len(kept)} kept, {len(skipped)} skipped" + (f", {len(failed)} FAILED" if failed else ""))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
